/**
 * One quarter of a tile: a column and row in half-tile units inside the kind's block on its sheet.
 */
type Quadrant = readonly [ number, number ];

/**
 * The four quarters one autotile shape draws, in the order top-left, top-right, bottom-left, bottom-right.
 */
type ShapeQuadrants = readonly [ Quadrant, Quadrant, Quadrant, Quadrant ];

